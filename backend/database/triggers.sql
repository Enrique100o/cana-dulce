-- Estas reglas también protegen el historial ante modificaciones SQL directas.
DELIMITER $$

CREATE TRIGGER lectura_congelada BEFORE UPDATE ON LECTURA
FOR EACH ROW
BEGIN
  IF EXISTS (SELECT 1 FROM INTENTO WHERE idLectura = OLD.idLectura)
    AND (
      NOT (NEW.titulo <=> OLD.titulo)
      OR NOT (NEW.contenido <=> OLD.contenido)
      OR NOT (NEW.grado <=> OLD.grado)
      OR NOT (NEW.dificultad <=> OLD.dificultad)
      OR NOT (NEW.categoria <=> OLD.categoria)
    )
  THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'CONTENIDO_BLOQUEADO';
  END IF;
END$$

CREATE TRIGGER pregunta_congelada_insert BEFORE INSERT ON PREGUNTA
FOR EACH ROW
BEGIN
  IF EXISTS (SELECT 1 FROM INTENTO WHERE idLectura = NEW.idLectura)
  THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'CONTENIDO_BLOQUEADO';
  END IF;
END$$

CREATE TRIGGER pregunta_congelada_update BEFORE UPDATE ON PREGUNTA
FOR EACH ROW
BEGIN
  IF EXISTS (SELECT 1 FROM INTENTO WHERE idLectura IN (OLD.idLectura, NEW.idLectura))
  THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'CONTENIDO_BLOQUEADO';
  END IF;
END$$

CREATE TRIGGER pregunta_congelada_delete BEFORE DELETE ON PREGUNTA
FOR EACH ROW
BEGIN
  IF EXISTS (SELECT 1 FROM INTENTO WHERE idLectura = OLD.idLectura)
  THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'CONTENIDO_BLOQUEADO';
  END IF;
END$$

CREATE TRIGGER opcion_congelada_insert BEFORE INSERT ON OPCION
FOR EACH ROW
BEGIN
  IF EXISTS (SELECT 1 FROM PREGUNTA p JOIN INTENTO i USING (idLectura) WHERE p.idPregunta = NEW.idPregunta)
  THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'CONTENIDO_BLOQUEADO';
  END IF;
END$$

CREATE TRIGGER opcion_congelada_update BEFORE UPDATE ON OPCION
FOR EACH ROW
BEGIN
  IF EXISTS (SELECT 1 FROM PREGUNTA p JOIN INTENTO i USING (idLectura) WHERE p.idPregunta IN (OLD.idPregunta, NEW.idPregunta))
  THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'CONTENIDO_BLOQUEADO';
  END IF;
END$$

CREATE TRIGGER opcion_congelada_delete BEFORE DELETE ON OPCION
FOR EACH ROW
BEGIN
  IF EXISTS (SELECT 1 FROM PREGUNTA p JOIN INTENTO i USING (idLectura) WHERE p.idPregunta = OLD.idPregunta)
  THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'CONTENIDO_BLOQUEADO';
  END IF;
END$$

CREATE TRIGGER intento_completado_inmutable BEFORE UPDATE ON INTENTO
FOR EACH ROW
BEGIN
  IF OLD.estado = 'COMPLETADO' THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'INTENTO_YA_COMPLETADO';
  END IF;
END$$

CREATE TRIGGER respuesta_no_modificable BEFORE UPDATE ON RESPUESTA
FOR EACH ROW
SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'RESPUESTA_INMUTABLE'$$

CREATE TRIGGER respuesta_no_eliminable BEFORE DELETE ON RESPUESTA
FOR EACH ROW
SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'RESPUESTA_INMUTABLE'$$

CREATE TRIGGER respuesta_pertenece_intento BEFORE INSERT ON RESPUESTA
FOR EACH ROW
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM INTENTO i JOIN PREGUNTA p ON p.idLectura = i.idLectura
    WHERE i.idIntento = NEW.idIntento AND p.idPregunta = NEW.idPregunta
      AND p.estado = 'ACTIVA' AND i.estado = 'EN_PROGRESO'
  ) THEN
    SIGNAL SQLSTATE '45000' SET MESSAGE_TEXT = 'RESPUESTA_AJENA';
  END IF;
END$$

DELIMITER ;
